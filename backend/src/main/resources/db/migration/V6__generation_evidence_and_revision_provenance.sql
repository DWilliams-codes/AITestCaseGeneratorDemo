  ADD CONSTRAINT uq_test_case_revisions_source_audit_event UNIQUE (source_audit_event_id);

-- Rows created before V6 cannot prove the exact provider adapter or validator binary.
UPDATE generation_runs
SET provider_adapter_version = 'legacy-unknown',
    result_contract_version = 'legacy-unknown',
    schema_version = 'manual-test-schema-v1',
    validator_version = 'legacy-unknown',
    source_requirement_version = (
      SELECT requirement.version
      FROM requirements requirement
      WHERE requirement.id = generation_runs.requirement_id
    ),
    source_snapshot_provenance = 'LEGACY_RECONSTRUCTED';

-- This reconstructs currently knowable criteria; it never claims to restore deleted history.
INSERT INTO generation_criterion_snapshots (
    generation_run_id,
    source_acceptance_criterion_id,
    criterion_key,
    description,
    sort_order,
    source_requirement_version,
    provenance
)
SELECT
    run.id,
    criterion.id,
    criterion.criterion_key,
    criterion.description,
    criterion.sort_order,
    requirement.version,
    'LEGACY_RECONSTRUCTED'
FROM generation_runs run
JOIN requirements requirement ON requirement.id = run.requirement_id
JOIN acceptance_criteria criterion ON criterion.requirement_id = requirement.id;

INSERT INTO snapshot_traceability_links (
    criterion_snapshot_id,
    test_case_id,
    coverage_type,
    confidence,
    created_at
)
SELECT
    snapshot.id,
    legacy.test_case_id,
    legacy.coverage_type,
    legacy.confidence,
    legacy.created_at
FROM traceability_links legacy
JOIN test_cases test_case ON test_case.id = legacy.test_case_id
JOIN generation_criterion_snapshots snapshot
  ON snapshot.generation_run_id = test_case.generation_run_id
 AND snapshot.source_acceptance_criterion_id = legacy.acceptance_criterion_id;
